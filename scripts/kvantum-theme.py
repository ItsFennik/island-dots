#!/usr/bin/env python3
"""Build a Kvantum theme ("Island") from an Island palette, for Qt5 + Qt6 apps.

    kvantum-theme.py <themes/id.json> [out_dir]   (default ~/.config/Kvantum/Island)

Starts from Kvantum's own KvArcDark (dark palettes) or KvArc (light) and recolours
every colour in its SVG + kvconfig:
  * greys are re-mapped along the base theme's bg→fg axis onto the palette's bg→fg
  * saturated colours become the palette accent, keeping their relative lightness
Then the [GeneralColors] (QPalette) roles are set straight from the palette.
"""
import colorsys, json, os, re, sys

pal = json.load(open(sys.argv[1]))
out = sys.argv[2] if len(sys.argv) > 2 else os.path.expanduser("~/.config/Kvantum/Island")
dark = bool(pal.get("dark", True))

BASE = "KvArcDark" if dark else "KvArc"
SRC = f"/usr/share/Kvantum/{BASE}"
BASE_BG, BASE_FG = ("#383c4a", "#d3dae3") if dark else ("#f5f6f7", "#5c616c")
BASE_ACCENT = "#5294e2"


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def hexc(c):
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v))) for v in c)


def light(c):
    return colorsys.rgb_to_hls(*(v / 255 for v in c))[1]


bg, fg, acc = rgb(pal["bg"]), rgb(pal["fg"]), rgb(pal["accent"])
lb, lf = light(rgb(BASE_BG)), light(rgb(BASE_FG))
acc_h, acc_l, acc_s = colorsys.rgb_to_hls(*(v / 255 for v in acc))
base_acc_l = light(rgb(BASE_ACCENT))
cache = {}


def remap(h6):
    if h6 in cache:
        return cache[h6]
    c = rgb(h6)
    hh, l, s = colorsys.rgb_to_hls(*(v / 255 for v in c))
    if s > 0.25 and 0.08 < l < 0.92:                     # chromatic → accent
        nl = max(0.0, min(1.0, acc_l + (l - base_acc_l)))
        r = hexc(v * 255 for v in colorsys.hls_to_rgb(acc_h, nl, acc_s))
    else:                                                # grey → bg..fg axis
        t = (l - lb) / (lf - lb)
        r = hexc(b + t * (f - b) for b, f in zip(bg, fg))
    cache[h6] = r
    return r


HEX = re.compile(r"#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?\b")


def recolour(text):
    return HEX.sub(lambda m: remap("#" + m.group(1).lower())[0:7] + (m.group(2) or ""), text)


os.makedirs(out, exist_ok=True)

svg = recolour(open(f"{SRC}/{BASE}.svg").read())

cfg = open(f"{SRC}/{BASE}.kvconfig").read()
cfg = re.sub(r"(=\s*)(white|black)\b", lambda m: m.group(1) + ("#ffffff" if m.group(2) == "white" else "#000000"), cfg)
cfg = recolour(cfg)


def a(h, alpha):  # "#rrggbb" + alpha byte
    return h + "%02x" % alpha


p = pal
general = {
    "window.color": p["bg"],
    "base.color": p["bg_alt"],
    "alt.base.color": p["surface"],
    "button.color": p["surface"],
    "light.color": p["overlay"],
    "mid.light.color": p["surface"],
    "dark.color": p["bg_alt"],
    "mid.color": p["overlay"],
    "highlight.color": p["accent"],
    "inactive.highlight.color": p["accent"],
    "text.color": p["fg"],
    "window.text.color": p["fg"],
    "button.text.color": p["fg"],
    "disabled.text.color": p["fg_faint"],
    "tooltip.text.color": p["fg"],
    "highlight.text.color": p["accent_fg"],
    "link.color": p["blue"],
    "link.visited.color": p["magenta"],
    "progress.indicator.text.color": p["accent_fg"],
}
sect = "[GeneralColors]\n" + "".join(f"{k}={v}\n" for k, v in general.items()) + "\n"
cfg = re.sub(r"\[GeneralColors\]\n.*?(?=^\[)", sect, cfg, flags=re.S | re.M)
cfg = f"# Generated by quickshell/island/scripts/kvantum-theme.py from {BASE} ({p.get('name', '')}). Edits get overwritten.\n" + cfg


def put(path, text):
    try:
        if open(path).read() == text:
            return
    except FileNotFoundError:
        pass
    with open(path + ".tmp", "w") as f:
        f.write(text)
    os.replace(path + ".tmp", path)


put(f"{out}/Island.svg", svg)
put(f"{out}/Island.kvconfig", cfg)

# Select the theme (keeps any other keys the user set in Kvantum Manager).
main = os.path.join(os.path.dirname(out), "kvantum.kvconfig")
try:
    txt = open(main).read()
except FileNotFoundError:
    txt = ""
if re.search(r"^theme=", txt, re.M):
    txt = re.sub(r"^theme=.*$", "theme=Island", txt, flags=re.M)
elif "[General]" in txt:
    txt = txt.replace("[General]", "[General]\ntheme=Island", 1)
else:
    txt = "[General]\ntheme=Island\n" + txt
put(main, txt)


# ── KDE apps (Dolphin, Kate…) read colours from kdeglobals, not the Qt palette ──
def kc(h):
    return ",".join(str(v) for v in rgb(h))


def group(bg_, bg_alt, fg_=p["fg"]):
    return {
        "BackgroundNormal": kc(bg_), "BackgroundAlternate": kc(bg_alt),
        "ForegroundNormal": kc(fg_), "ForegroundInactive": kc(p["fg_dim"]),
        "ForegroundActive": kc(p["accent"]), "ForegroundLink": kc(p["blue"]),
        "ForegroundVisited": kc(p["magenta"]), "ForegroundNegative": kc(p["red"]),
        "ForegroundNeutral": kc(p["yellow"]), "ForegroundPositive": kc(p["green"]),
        "DecorationFocus": kc(p["accent"]), "DecorationHover": kc(p["accent"]),
    }


kde = {
    "Colors:Window": group(p["bg"], p["surface"]),
    "Colors:View": group(p["bg_alt"], p["bg"]),
    "Colors:Button": group(p["surface"], p["overlay"]),
    "Colors:Selection": dict(group(p["accent"], p["accent"], p["accent_fg"]),
                             ForegroundInactive=kc(p["accent_fg"]), ForegroundActive=kc(p["accent_fg"])),
    "Colors:Tooltip": group(p["surface"], p["bg"]),
    "Colors:Complementary": group(p["bg"], p["surface"]),
    "Colors:Header": group(p["bg"], p["surface"]),
    "Colors:Header][Inactive": group(p["bg"], p["surface"]),
    "WM": {"activeBackground": kc(p["bg"]), "activeForeground": kc(p["fg"]),
           "inactiveBackground": kc(p["bg"]), "inactiveForeground": kc(p["fg_dim"])},
}

kg = os.path.join(os.path.dirname(os.path.dirname(out)), "kdeglobals")
try:
    lines = open(kg).read().splitlines()
except FileNotFoundError:
    lines = []
keep, cur, general = [], None, []
for line in lines:
    s_ = line.strip()
    if s_.startswith("[") and s_.endswith("]"):
        cur = s_[1:-1]
        if cur == "General":
            continue
    if cur in kde:
        continue
    if cur == "General":
        if not s_.startswith("ColorScheme="):
            general.append(line)
        continue
    keep.append(line)
text = "\n".join(keep).strip()
text += ("\n\n" if text else "") + "[General]\nColorScheme=Island\n" + "".join(l + "\n" for l in general if l.strip())
for name, kv in kde.items():
    text += f"\n[{name}]\n" + "".join(f"{k}={v}\n" for k, v in kv.items())
put(kg, text)

# Same scheme as a named .colors file (KColorSchemeManager looks it up by name).
cs_dir = os.path.join(os.environ.get("XDG_DATA_HOME", os.path.expanduser("~/.local/share")), "color-schemes")
os.makedirs(cs_dir, exist_ok=True)
cs = "[General]\nName=Island\nColorScheme=Island\n"
for name, kv in kde.items():
    cs += f"\n[{name}]\n" + "".join(f"{k}={v}\n" for k, v in kv.items())
put(os.path.join(cs_dir, "Island.colors"), cs)
