#!/bin/sh
# Display changes for the Settings "Displays" pane (Hyprland).
#   displays.sh apply OUTPUT MODE POSITION SCALE TRANSFORM   → applies live (not saved)
#   displays.sh save                                          → writes every monitor's current
#        state to ~/.config/hypr/displays.lua (loaded last by hyprland.lua, so it wins)
set -eu
OUT="${XDG_CONFIG_HOME:-$HOME/.config}/hypr/displays.lua"

case ${1:-} in
apply)
    r=$(hyprctl eval "hl.monitor({ output = \"$2\", mode = \"$3\", position = \"$4\", scale = $5, transform = $6 })")
    [ "$r" = ok ] || { echo "$r" >&2; exit 1; } ;;
save)
    tmp=$(mktemp)
    {
        echo "-- Generated by quickshell/island (Settings → Displays). Overrides monitor rules above it."
        hyprctl -j monitors all | jq -r '.[] | select(.disabled | not) |
            "hl.monitor({ output = \"\(.name)\", mode = \"\(.width)x\(.height)@\(.refreshRate * 100 | round / 100)\", position = \"\(.x)x\(.y)\", scale = \(.scale), transform = \(.transform) })"'
    } > "$tmp"
    mv "$tmp" "$OUT" ;;
*)
    echo "usage: $0 apply OUTPUT MODE POSITION SCALE TRANSFORM | save" >&2; exit 2 ;;
esac
