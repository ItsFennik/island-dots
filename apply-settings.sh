#!/usr/bin/env bash
# Apply ~/.config/island/settings.json (merged over defaults.json) to
# Hyprland / niri / Sway and Foot. Run by Island Settings on every change; safe to run by
# hand. Only files whose content changed are rewritten. (The bar reads the
# settings itself.)

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CFG="${XDG_CONFIG_HOME:-$HOME/.config}"
USER_FILE="$CFG/island/settings.json"

user='{}'
[ -s "$USER_FILE" ] && user="$(jq -c 'if type == "object" then . else {} end' "$USER_FILE" 2>/dev/null || echo '{}')"

# Load merged settings as shell variables (s_<key>) in one jq call.
eval "$(jq -r --argjson u "$user" '. * $u | to_entries[] | "s_\(.key)=\(.value|tostring|@sh)"' "$HERE/defaults.json")"

put() { local f="$1" new; new="$(cat)"; [ -f "$f" ] && [ "$new" = "$(<"$f")" ] && return 1; printf '%s\n' "$new" > "$f"; }

# ── Hyprland ──────────────────────────────────────────────────────────
anim=""
if [ "$s_animations" = true ]; then
  anim="hl.animation({ leaf = \"global\", enabled = true, speed = $s_animSpeed, bezier = \"default\" })
hl.animation({ leaf = \"windows\", enabled = true, style = \"$s_windowAnim\", speed = $s_animSpeed, bezier = \"default\" })
hl.animation({ leaf = \"workspaces\", enabled = true, style = \"$s_workspaceAnim\", speed = $s_animSpeed, bezier = \"default\" })"
else
  anim="hl.animation({ leaf = \"global\", enabled = false, speed = 1, bezier = \"default\" })"
fi

hypr="hl.config({
    general = { gaps_in = $s_gapsIn, gaps_out = $s_gapsOut, border_size = $s_borderSize, layout = \"$s_layout\" },
    decoration = {
        rounding = $s_rounding,
        active_opacity = $s_activeOpacity,
        inactive_opacity = $s_inactiveOpacity,
        dim_inactive = $s_dimInactive,
        blur = { enabled = $s_blur, size = $s_blurSize, passes = $s_blurPasses },
    },
    input = {
        follow_mouse = $s_followMouse,
        sensitivity = $s_sensitivity,
        accel_profile = \"$s_accelProfile\",
        natural_scroll = $s_naturalScroll,
        repeat_rate = $s_repeatRate,
        repeat_delay = $s_repeatDelay,
        numlock_by_default = $s_numlock,
    },
})
$anim"

cursor_start="hl.on(\"hyprland.start\", function() hl.exec_cmd(\"hyprctl setcursor $s_cursorTheme $s_cursorSize\") end)"
printf -- '-- Generated by quickshell/island/apply-settings.sh from ~/.config/island/settings.json\n%s\n%s\n' "$hypr" "$cursor_start" | put "$CFG/hypr/settings.lua" || true
command -v hyprctl >/dev/null && hyprctl eval "$hypr" >/dev/null 2>&1 || true

# ── niri ──────────────────────────────────────────────────────────────
# Written to ~/.config/niri/island.kdl; add  include "island.kdl"  near the end of
# config.kdl (niri 25.11+). niri reloads its config on change, so this applies live.
if [ -d "$CFG/niri" ] || command -v niri >/dev/null; then
  mkdir -p "$CFG/niri"
  b() { [ "$1" = true ] && printf '%s' "$2" || true; }
  ffm=""; [ "$s_followMouse" != 0 ] && ffm="focus-follows-mouse"
  if [ "$s_animations" = true ]; then niri_anim="animations { slowdown $(awk -v s="$s_animSpeed" 'BEGIN{ if (s <= 0) s = 1; printf "%.2f", 2 / s }'); }"
  else niri_anim="animations { off; }"; fi
  put "$CFG/niri/island.kdl" <<NIRI || true
// Generated by quickshell/island/apply-settings.sh from ~/.config/island/settings.json
layout {
    gaps $s_gapsOut
    border { width $s_borderSize; }
    focus-ring { off; }
}
input {
    keyboard { repeat-rate $s_repeatRate; repeat-delay $s_repeatDelay; $(b "$s_numlock" "numlock;") }
    mouse { accel-speed $s_sensitivity; accel-profile "$s_accelProfile"; $(b "$s_naturalScroll" "natural-scroll;") }
    touchpad { $(b "$s_naturalScroll" "natural-scroll;") }
    $ffm
}
cursor { xcursor-theme "$s_cursorTheme"; xcursor-size $s_cursorSize; }
window-rule { geometry-corner-radius $s_rounding; clip-to-geometry true; }
window-rule { match is-active=true; opacity $s_activeOpacity; }
window-rule { match is-active=false; opacity $s_inactiveOpacity; }
$niri_anim
NIRI
fi

# ── Sway / Scroll ─────────────────────────────────────────────────────
# Applied live over IPC, and saved to ~/.config/sway/island.conf for the next login
# (add  include island.conf  to the sway config).
if [ -n "${SWAYSOCK:-}" ] || [ -d "$CFG/sway" ]; then
  mkdir -p "$CFG/sway"
  onoff() { [ "$1" = true ] && echo enabled || echo disabled; }
  sway_cfg="gaps inner $s_gapsIn
gaps outer $s_gapsOut
default_border pixel $s_borderSize
default_floating_border pixel $s_borderSize
focus_follows_mouse $([ "$s_followMouse" != 0 ] && echo yes || echo no)
input type:keyboard repeat_rate $s_repeatRate
input type:keyboard repeat_delay $s_repeatDelay
input type:keyboard xkb_numlock $(onoff "$s_numlock")
input type:pointer accel_profile $s_accelProfile
input type:pointer pointer_accel $s_sensitivity
input type:pointer natural_scroll $(onoff "$s_naturalScroll")
input type:touchpad natural_scroll $(onoff "$s_naturalScroll")
seat * xcursor_theme $s_cursorTheme $s_cursorSize"
  printf '# Generated by quickshell/island/apply-settings.sh. Change these in Island Settings.\n%s\n' "$sway_cfg" | put "$CFG/sway/island.conf" || true
  if [ -n "${SWAYSOCK:-}" ]; then
    msg=swaymsg; [[ "${XDG_CURRENT_DESKTOP:-}" == *scroll* ]] && command -v scrollmsg >/dev/null && msg=scrollmsg
    $msg "gaps inner all set $s_gapsIn; gaps outer all set $s_gapsOut; [all] border pixel $s_borderSize" >/dev/null 2>&1 || true
    while IFS= read -r l; do $msg "$l" >/dev/null 2>&1 || true; done <<<"$sway_cfg"
  fi
fi

# ── Bar ───────────────────────────────────────────────────────────────
# The bar, launcher and menus live in Quickshell and read settings.json directly;
# only the blur behind them is a Hyprland layer rule.
command -v hyprctl >/dev/null && hyprctl eval "hl.layer_rule({ name = \"island-bar-blur\", match = { namespace = \"island-bar\" }, blur = $s_barBlur, ignore_alpha = 0.3 })" >/dev/null 2>&1 || true

# ── GTK theme, icons, cursor ──────────────────────────────────────────
for v in gtk-3.0 gtk-4.0; do
  f="$CFG/$v/settings.ini"; mkdir -p "$CFG/$v"; [ -f "$f" ] || printf '[Settings]\n' > "$f"
  setini() { grep -q "^$1=" "$f" && sed -i "s|^$1=.*|$1=$2|" "$f" || printf '%s=%s\n' "$1" "$2" >> "$f"; }
  setini gtk-icon-theme-name "$s_iconTheme"
  setini gtk-cursor-theme-name "$s_cursorTheme"
  setini gtk-cursor-theme-size "$s_cursorSize"
  [ "$s_gtkTheme" != auto ] && setini gtk-theme-name "$s_gtkTheme"
done
mkdir -p "$HOME/.icons/default"
printf '[Icon Theme]\nInherits=%s\n' "$s_cursorTheme" | put "$HOME/.icons/default/index.theme" || true
if command -v gsettings >/dev/null; then
  gsettings set org.gnome.desktop.interface icon-theme "$s_iconTheme"
  gsettings set org.gnome.desktop.interface cursor-theme "$s_cursorTheme"
  gsettings set org.gnome.desktop.interface cursor-size "$s_cursorSize"
  [ "$s_gtkTheme" != auto ] && gsettings set org.gnome.desktop.interface gtk-theme "$s_gtkTheme"
fi
command -v hyprctl >/dev/null && hyprctl setcursor "$s_cursorTheme" "$s_cursorSize" >/dev/null 2>&1 || true

# GTK theme switched back to auto: let apply-theme recolour adw-gtk3 again.
STATE="${XDG_STATE_HOME:-$HOME/.local/state}/island"; mkdir -p "$STATE"
if printf '%s\n' "$s_gtkTheme" | put "$STATE/gtk-theme"; then
  [ -r "$STATE/theme" ] && "$HERE/apply-theme.sh" --restore >/dev/null 2>&1 &
fi

# Quickshell reads its icon theme from a pragma at startup: rewrite it and restart the bar.
if ! grep -qx "//@ pragma IconTheme $s_iconTheme" "$HERE/shell.qml"; then
  sed -i "s|^//@ pragma IconTheme .*|//@ pragma IconTheme $s_iconTheme|" "$HERE/shell.qml"
  setsid -f sh -c 'sleep 0.5; qs -c island kill >/dev/null 2>&1; sleep 0.5; exec qs -c island -n -d' >/dev/null 2>&1
fi

# ── Wallpaper colours (matugen) ───────────────────────────────────────
key="$s_matugen $s_matugenScheme $s_matugenMode $s_matugenPrefer"
if [ "$s_matugen" = true ]; then
  printf '%s\n' "$key" | put "$STATE/matugen" && "$HERE/scripts/matugen-theme.sh" >/dev/null 2>&1 &
else
  rm -f "$STATE/matugen"
fi

# ── Foot (new terminals) ──────────────────────────────────────────────
put "$CFG/foot/settings.ini" <<EOF || true
# Generated by quickshell/island/apply-settings.sh. Change these in Island Settings.
[main]
font=$s_termFont:size=$s_termFontSize
pad=${s_termPadding}x${s_termPadding}
[colors-dark]
alpha=$s_termOpacity
EOF

exit 0
