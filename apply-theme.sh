#!/usr/bin/env bash
# Apply an Island theme everywhere: GTK 3/4, Qt 5/6 (Kvantum), Hyprland / niri / Sway borders, Foot.
# (The bar picks the theme up itself from the state file.)
#
#   apply-theme.sh <id>        id = file name in themes/ without .json (e.g. catppuccin-mocha)
#   apply-theme.sh --restore   re-apply the saved theme (cheap; skips if nothing saved)
#
# Every target file is regenerated from the palette in themes/<id>.json.
# GTK uses adw-gtk3 (+ libadwaita) recoloured through a marked block in gtk.css,
# so no third-party GTK theme packages are needed.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CFG="${XDG_CONFIG_HOME:-$HOME/.config}"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/island"
STATE_FILE="$STATE_DIR/theme"
mkdir -p "$STATE_DIR"

id="${1:-}"
if [ "$id" = "--restore" ]; then
  [ -r "$STATE_FILE" ] || exit 0
  id="$(<"$STATE_FILE")"
fi
file="$HERE/themes/$id.json"
[ -n "$id" ] && [ -r "$file" ] || { echo "usage: $0 <theme-id> | --restore" >&2; ls "$HERE/themes" >&2; exit 1; }

# Load the palette into shell variables in one jq call.
eval "$(jq -r 'to_entries[] | select(.key != "name") | "\(.key)=\(.value|tostring|@sh)"' "$file")"

h() { printf '%s' "${1#\#}"; }                       # "#aabbcc" -> "aabbcc"
rgb() { local x; x=$(h "$1"); printf '%d, %d, %d' "0x${x:0:2}" "0x${x:2:2}" "0x${x:4:2}"; }

# Write only when content changed.
put() { local f="$1" new; new="$(cat)"; [ -f "$f" ] && [ "$new" = "$(<"$f")" ] && return 0; printf '%s\n' "$new" > "$f"; }

# ── Foot (new terminals) ──────────────────────────────────────────────
mkdir -p "$CFG/foot/themes"
put "$CFG/foot/themes/island" <<EOF
# Generated by quickshell/island/apply-theme.sh ($id)
[colors-dark]
foreground=$(h "$fg")
background=$(h "$bg")
regular0=$(h "$surface")
regular1=$(h "$red")
regular2=$(h "$green")
regular3=$(h "$yellow")
regular4=$(h "$blue")
regular5=$(h "$magenta")
regular6=$(h "$cyan")
regular7=$(h "$fg_dim")
bright0=$(h "$fg_faint")
bright1=$(h "$red")
bright2=$(h "$green")
bright3=$(h "$yellow")
bright4=$(h "$blue")
bright5=$(h "$magenta")
bright6=$(h "$cyan")
bright7=$(h "$fg")
selection-foreground=$(h "$bg")
selection-background=$(h "$fg_dim")
cursor=$(h "$bg") $(h "$accent")
EOF

# ── Hyprland borders (saved for reloads + applied live) ───────────────
hypr_lua="hl.config({ general = { col = { active_border = \"rgb($(h "$accent"))\", inactive_border = \"rgb($(h "$surface"))\" } }, group = { col = { border_active = \"rgb($(h "$accent"))\", border_inactive = \"rgb($(h "$surface"))\", border_locked_active = \"rgb($(h "$red"))\", border_locked_inactive = \"rgb($(h "$surface"))\" }, groupbar = { col = { active = \"rgb($(h "$accent"))\", inactive = \"rgb($(h "$surface"))\" }, text_color = \"rgb($(h "$accent_fg"))\", text_color_inactive = \"rgb($(h "$fg_dim"))\" } } })"
put "$CFG/hypr/theme.lua" <<EOF
-- Generated by quickshell/island/apply-theme.sh ($id)
$hypr_lua
EOF
command -v hyprctl >/dev/null && hyprctl eval "$hypr_lua" >/dev/null 2>&1 || true

# ── MangoWC borders (~/.config/mango/theme.conf, sourced by config.conf) ──
if [ -d "$CFG/mango" ] || command -v mango >/dev/null; then
  mkdir -p "$CFG/mango"
  put "$CFG/mango/theme.conf" <<MANGO
# Generated by quickshell/island/apply-theme.sh ($id). Change the theme in Island.
focus_color=0x$(h "$accent")ff
border_color=0x$(h "$surface")ff
urgent_color=0x$(h "$red")ff
MANGO
  pgrep -x mango >/dev/null && mmsg dispatch reload_config >/dev/null 2>&1 || true
fi

# ── niri / Sway borders ───────────────────────────────────────────────
if [ -d "$CFG/niri" ] || command -v niri >/dev/null; then
  mkdir -p "$CFG/niri"
  put "$CFG/niri/island-theme.kdl" <<NIRI
// Generated by quickshell/island/apply-theme.sh ($id). Add to config.kdl: include "island-theme.kdl"
layout { border { active-color "$accent"; inactive-color "$surface"; urgent-color "$red"; } }
NIRI
fi
if [ -n "${SWAYSOCK:-}" ] || [ -d "$CFG/sway" ]; then
  mkdir -p "$CFG/sway"
  sway_theme="client.focused $accent $accent $accent_fg $accent $accent
client.focused_inactive $surface $surface $fg_dim $surface $surface
client.unfocused $surface $surface $fg_dim $surface $surface
client.urgent $red $red $accent_fg $red $red"
  printf '# Generated by quickshell/island/apply-theme.sh (%s). Add to the sway config: include island-theme.conf\n%s\n' "$id" "$sway_theme" | put "$CFG/sway/island-theme.conf"
  if [ -n "${SWAYSOCK:-}" ]; then
    while IFS= read -r l; do swaymsg "$l" >/dev/null 2>&1 || true; done <<<"$sway_theme"
  fi
fi

# ── Discord (Vesktop; Midnight base, recoloured) ──────────────────────
# Vesktop hot-reloads files in its themes dir, so switching is live.
if [ -d "$CFG/vesktop" ]; then
  mkdir -p "$CFG/vesktop/themes"
  name="$(jq -r .name "$file")"
  font="$(jq -r '.widgetFont // empty' "$CFG/island/settings.json" 2>/dev/null || true)"
  [ -n "$font" ] || font="$(jq -r '.widgetFont // "sans-serif"' "$HERE/defaults.json")"
  # five steps per hue: lighter → darker
  shades() { local n="$1" c="$2"
    printf '  --%s-1: color-mix(in srgb, %s, white 18%%);\n  --%s-2: %s;\n  --%s-3: %s;\n  --%s-4: color-mix(in srgb, %s, black 12%%);\n  --%s-5: color-mix(in srgb, %s, black 24%%);\n' \
      "$n" "$c" "$n" "$c" "$n" "$c" "$n" "$c" "$n" "$c"; }
  put "$CFG/vesktop/themes/island.theme.css" <<EOF
/**
 * @name Island
 * @description Follows the Island shell theme ($name). Generated by quickshell/island/apply-theme.sh — edits get overwritten.
 * @author fennik
 * @version 1.0.0
 */
@import url('https://refact0r.github.io/midnight-discord/build/midnight.css');

body {
  --font: '$font';
  --code-font: '$font';
  font-weight: 400;

  --gap: 10px;
  --divider-thickness: 3px;
  --border-thickness: 1px;

  --animations: on;
  --list-item-transition: 0.2s ease;
  --dms-icon-svg-transition: 0.4s ease;
  --border-hover-transition: 0.2s ease;

  --top-bar-height: var(--gap);
  --top-bar-button-position: titlebar;
  --top-bar-title-position: off;
  --subtle-top-bar-title: off;

  --custom-window-controls: on;
  --window-control-size: 14px;

  --custom-dms-icon: off;
  --dms-icon-color-before: var(--icon-subtle);
  --dms-icon-color-after: var(--white);
  --custom-dms-background: off;

  --background-image: off;
  --transparency-tweaks: off;
  --remove-bg-layer: off;
  --panel-blur: off;
  --blur-amount: 12px;
  --bg-floating: var(--bg-3);

  --custom-chatbar: separated;
  --chatbar-height: 56px;
  --small-user-panel: off;
}

:root {
  --colors: on;

  /* text */
  --text-0: $accent_fg;
  --text-1: $fg;
  --text-2: $fg;
  --text-3: $fg_dim;
  --text-4: $fg_faint;
  --text-5: color-mix(in srgb, $fg_faint, $bg 35%);

  /* backgrounds */
  --bg-1: $overlay;
  --bg-2: $surface;
  --bg-3: $bg_alt;
  --bg-4: $bg;
  --hover: color-mix(in srgb, $fg 7%, transparent);
  --active: color-mix(in srgb, $fg 13%, transparent);
  --active-2: color-mix(in srgb, $fg 18%, transparent);
  --message-hover: color-mix(in srgb, $fg 4%, transparent);

  /* accent */
  --accent-1: $accent;
  --accent-2: color-mix(in srgb, $accent 55%, $bg);
  --accent-3: $accent;
  --accent-4: color-mix(in srgb, $accent, $fg 15%);
  --accent-5: color-mix(in srgb, $accent, $bg 15%);
  --accent-new: $red;

  --mention: linear-gradient(to right, color-mix(in srgb, $accent 12%, transparent) 40%, transparent);
  --mention-hover: linear-gradient(to right, color-mix(in srgb, $accent 18%, transparent) 40%, transparent);
  --reply: linear-gradient(to right, color-mix(in srgb, $fg_dim 10%, transparent) 40%, transparent);
  --reply-hover: linear-gradient(to right, color-mix(in srgb, $fg_dim 15%, transparent) 40%, transparent);

  /* status */
  --online: $green;
  --dnd: $red;
  --idle: $yellow;
  --streaming: $magenta;
  --offline: $fg_faint;

  /* borders */
  --border-light: var(--hover);
  --border: $overlay;
  --border-hover: color-mix(in srgb, $accent 50%, $overlay);
  --button-border: color-mix(in srgb, $fg 10%, transparent);

  /* base hues */
$(shades red "$red")
$(shades green "$green")
$(shades blue "$blue")
$(shades yellow "$yellow")
$(shades purple "$magenta")
}

/* small fixes on top of Midnight */
[class*="divider"]:not([class*="isUnread"]) { border-color: var(--bg-2) !important; }
[class*="timestamp"], [class*="timestamp"] time { color: var(--text-4) !important; }
[class*="messageContent"] { color: var(--text-3) !important; }
::selection { background: color-mix(in srgb, $accent 35%, transparent); color: $fg; }
EOF
fi

# ── Qt 5 / 6 (Kvantum "Island" theme, recoloured from KvArc) ──────────
# Apps pick it up via QT_STYLE_OVERRIDE=kvantum (hypr/island.lua); new windows only.
if [ -d /usr/share/Kvantum ] && command -v python3 >/dev/null; then
  python3 "$HERE/scripts/kvantum-theme.py" "$file" "$CFG/Kvantum/Island" || true
fi

# ── GTK 3 / 4 ─────────────────────────────────────────────────────────
# Only when the GTK theme is "auto" (adw-gtk3 recoloured). With another GTK theme
# chosen in Island Settings, our colour block is removed so that theme looks as designed.
gtk_choice="$(cat "$STATE_DIR/gtk-theme" 2>/dev/null || echo auto)"
if [ "$gtk_choice" != auto ]; then
  for v in gtk-3.0 gtk-4.0; do
    f="$CFG/$v/gtk.css"
    [ -f "$f" ] && sed '/\/\* island theme begin \*\//,/\/\* island theme end \*\//d' "$f" | put "$f"
  done
  printf '%s\n' "$id" > "$STATE_FILE"
  exit 0
fi
pairs=(
  accent_color "$accent"  accent_bg_color "$accent"  accent_fg_color "$accent_fg"
  destructive_color "$red" destructive_bg_color "$red" destructive_fg_color "$bg"
  error_color "$red" error_bg_color "$red" error_fg_color "$bg"
  success_color "$green" success_bg_color "$green" success_fg_color "$bg"
  warning_color "$yellow" warning_bg_color "$yellow" warning_fg_color "$bg"
  window_bg_color "$bg" window_fg_color "$fg"
  view_bg_color "$bg_alt" view_fg_color "$fg"
  headerbar_bg_color "$surface" headerbar_fg_color "$fg"
  headerbar_backdrop_color "$bg" headerbar_border_color "$overlay"
  popover_bg_color "$surface" popover_fg_color "$fg"
  dialog_bg_color "$surface" dialog_fg_color "$fg"
  card_bg_color "$surface" card_fg_color "$fg"
  sidebar_bg_color "$bg_alt" sidebar_fg_color "$fg"
  sidebar_backdrop_color "$bg" sidebar_border_color "$overlay"
  secondary_sidebar_bg_color "$bg_alt" secondary_sidebar_fg_color "$fg"
  overview_bg_color "$bg_alt" overview_fg_color "$fg"
  thumbnail_bg_color "$surface" thumbnail_fg_color "$fg"
  borders "$overlay"
)
gtk3="" vars=""
for ((i = 0; i < ${#pairs[@]}; i += 2)); do
  gtk3+="@define-color ${pairs[i]} ${pairs[i+1]};"$'\n'
  vars+="  --${pairs[i]//_/-}: ${pairs[i+1]};"$'\n'
done
for n in bg:window_bg fg:window_fg base:view_bg text:view_fg selected_bg:accent_bg selected_fg:accent_fg; do
  gtk3+="@define-color theme_${n%%:*}_color @${n#*:}_color;"$'\n'
done
gtk4="$gtk3:root {"$'\n'"$vars}"$'\n'   # libadwaita 1.6+ reads CSS variables; GTK 3 rejects them

for v in gtk-3.0 gtk-4.0; do
  f="$CFG/$v/gtk.css"
  mkdir -p "$CFG/$v"; [ -f "$f" ] || : > "$f"
  [ -f "$f.pre-island" ] || cp "$f" "$f.pre-island"          # one-time backup
  [ "$v" = gtk-3.0 ] && block="$gtk3" || block="$gtk4"
  rest="$(sed '/\/\* island theme begin \*\//,/\/\* island theme end \*\//d' "$f")"
  # A gtk.css symlinked into a read-only system theme can't take our block: skip it, don't abort.
  printf '%s\n\n/* island theme begin */\n%s/* island theme end */\n' "$rest" "$block" | put "$f" 2>/dev/null \
    || echo "apply-theme: $f is not writable (symlink?), GTK $v colours skipped" >&2
  [ -f "$CFG/$v/settings.ini" ] && sed -i \
    -e "s|^gtk-theme-name=.*|gtk-theme-name=adw-gtk3$($dark && echo -dark)|" \
    -e "s|^gtk-application-prefer-dark-theme=.*|gtk-application-prefer-dark-theme=$($dark && echo 1 || echo 0)|" \
    "$CFG/$v/settings.ini"
done

if command -v gsettings >/dev/null; then
  gtk_theme="adw-gtk3$($dark && echo -dark)"
  gsettings set org.gnome.desktop.interface color-scheme "$($dark && echo prefer-dark || echo prefer-light)"
  # Blip the theme name so running GTK 3 apps reload gtk.css.
  gsettings set org.gnome.desktop.interface gtk-theme Default
  sleep 0.15
  gsettings set org.gnome.desktop.interface gtk-theme "$gtk_theme"
fi

printf '%s\n' "$id" > "$STATE_FILE"
